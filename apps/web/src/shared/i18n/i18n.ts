function getInitialLocale(): 'en' | 'vi' {
  return localStorage.getItem('ml-path-locale') === 'en' ? 'en' : 'vi';
}

export function createAppI18n(): i18n {
  const instance = createInstance();

  void instance.init({
    fallbackLng: ['vi', 'en'],
    initAsync: false,
    interpolation: {
      escapeValue: false,
    },
    lng: getInitialLocale(),
    resources,
  });

  return instance;
}
